"""The contract between bpmn8n and its n8n nodes: the X-Bpmn8n-* headers, the request bodies the nodes send (and
the task reply they read), and one version for both. `manage.py contract --ts` writes them as TypeScript into
n8n-nodes-bpmn8n/nodes/shared/contract.ts (a test fails when it is stale). The nodes send their version in
X-Bpmn8n-Contract; a server that speaks another one still answers, with an X-Bpmn8n-Warning the node shows."""
import hashlib
import json
from functools import cache
from pathlib import Path

from ..core.headers import HEADERS
from .gateways import ConditionsIn, GatewayIn
from .messages import SubscriptionIn
from .tasks import RunIn, RunOut
from .usertasks import UserTaskIn

API_VERSION = "1"
SHAPES = (RunIn, RunOut, GatewayIn, ConditionsIn, UserTaskIn, SubscriptionIn)
TS_FILE = Path(__file__).resolve().parents[2] / "n8n-nodes-bpmn8n" / "nodes" / "shared" / "contract.ts"


def schemas():
    return {shape.__name__: shape.model_json_schema() for shape in SHAPES}


@cache
def version():
    """The API version and a digest of the headers and shapes: any change to them is another contract."""
    digest = hashlib.sha256(json.dumps([HEADERS, schemas()], sort_keys=True).encode()).hexdigest()
    return f"{API_VERSION}.{digest[:8]}"


def mismatch(sent):
    """The warning for nodes built for contract `sent`; empty when it is this server's (or not sent)."""
    if not sent or sent == version():
        return ""
    return (f"the bpmn8n nodes speak contract {sent[:40]}, this server {version()}: "
            "rebuild n8n-nodes-bpmn8n from the server's version (manage.py contract --ts, npm run build)")


def middleware(get_response):
    """A call from nodes built for another contract still runs; its answer carries the warning."""
    def middleware(request):
        response = get_response(request)
        if warning := mismatch(request.headers.get(HEADERS["contract"], "")):
            response[HEADERS["warning"]] = warning
        return response
    return middleware


def literal(value):
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'" if isinstance(value, str) else json.dumps(value)


def ts_type(schema):
    """A JSON schema (as pydantic writes them) as a TypeScript type."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(s) for s in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(literal(v) for v in schema["enum"])
    if "const" in schema:
        return literal(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        values = schema.get("additionalProperties")
        return f"{{ [key: string]: {ts_type(values) if isinstance(values, dict) else 'unknown'} }}"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def interface(name, schema):
    required = set(schema.get("required", ()))
    fields = [f"\t{field}{'' if field in required else '?'}: {ts_type(s)};" for field, s in schema["properties"].items()]
    return "\n".join([f"export interface {name} {{", *fields, "}"])


def typescript():
    """contract.ts: the version, the header names and the shapes as interfaces."""
    shapes, defs = schemas(), {}
    for schema in shapes.values():
        defs.update(schema.pop("$defs", {}))
    headers = "\n".join(f"\t{key}: {literal(name)}," for key, name in HEADERS.items())
    return "\n\n".join([
        "// Generated by `python manage.py contract --ts` from bpmn8n's own definitions (bpmn8n/api/contract.py):\n"
        "// do not edit. The nodes send CONTRACT_VERSION; a server that speaks another one answers with a warning.",
        f"export const CONTRACT_VERSION = {literal(version())};",
        f"export const HEADERS = {{\n{headers}\n}} as const;",
        *(interface(name, schema) for name, schema in {**defs, **shapes}.items()),
    ]) + "\n"
